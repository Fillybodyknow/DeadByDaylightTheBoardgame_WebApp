/** The English name's key in THAI_NAMES: upper case, accents and punctuation gone ("Coup de Grâce" → "COUP DE GRACE"). */
export const thaiKey = (en: string) => en.normalize('NFD').replace(/\p{M}/gu, '').toUpperCase().replace(/[’']/g, "'").replace(/[^A-Z0-9&']+/g, ' ').trim()

/** The Thai name of a perk, power or Guard, from its English name; undefined when there is none. */
export const thaiName = (en: string): string | undefined => THAI_NAMES[thaiKey(en)]
